/** Resolve a dot-path key against a locale dictionary.
 * Falls back to the key itself when missing. Supports {var} interpolation. */
export function translate(
  lang: Locale,
  key: string,
  vars?: Record<string, string | number>
): string {
  const parts = key.split(".");
  let node: DictNode = dictionary[lang];
  for (const part of parts) {
    if (node && typeof node === "object" && part in node) {
      const next: DictNode | undefined = node[part];
      if (next === undefined) return key;
      node = next;
    } else {
      return key;
    }
  }
  if (typeof node !== "string") return key;
  if (vars) {
    return node.replace(/\{(\w+)\}/g, (m, name) =>
      name in vars ? String(vars[name]) : m
    );
  }
  return node;
}
